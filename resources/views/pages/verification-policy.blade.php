                </div>
                <div class="p-4">
                    <strong class="text-ink-primary block mb-1">5. Territory Availability & Exclusivity</strong>
                    <p class="text-ink-secondary text-xs leading-relaxed">Verification of state, city, and district territory schedules, including radius protection clauses to prevent unit cannibalization.</p>
                </div>
                <div class="p-4">
                    <strong class="text-ink-primary block mb-1">6. Itemized Financial Outlay Provenance</strong>
                    <p class="text-ink-secondary text-xs leading-relaxed">Disclosed fee components (franchise fee, fit-out CapEx, equipment, initial inventory, refundable deposits, royalty) with documented source citations.</p>
                </div>
                <div class="p-4">
                    <strong class="text-ink-primary block mb-1">7. Infrastructure & Regulatory Licensing</strong>
                    <p class="text-ink-secondary text-xs leading-relaxed">Commercial power load, minimum carpet area, drainage, and applicable statutory licenses (FSSAI, GST, Shop & Establishment, RBI CSP mandates).</p>
                </div>
                <div class="p-4">
